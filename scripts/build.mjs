#!/usr/bin/env node
/**
 * BotForge build pipeline.
 *
 *  1. regenerates the frontend bot catalog from the template registry
 *  2. bundles the control plane (Node.js) and the Cloudflare Worker
 *  3. copies the static frontend into dist/frontend
 *  4. fails the build when banned placeholders or emoji leak into shipped assets
 */
import { cp, mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { build as esbuild } from 'esbuild';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dist = join(root, 'dist');

const NODE_EXTERNALS = [
  'fastify',
  '@fastify/cors',
  '@fastify/helmet',
  '@fastify/rate-limit',
  '@fastify/static',
  'pg',
  'zod',
  'node:*'
];

const BANNED_PATTERNS = [
  { pattern: /\bTODO\b/, label: 'TODO' },
  { pattern: /\bFIXME\b/, label: 'FIXME' },
  { pattern: /not implemented/i, label: 'not implemented' },
  { pattern: /Coming soon/i, label: 'Coming soon' }
];

const EMOJI_PATTERN = /[\u{1F300}-\u{1FAFF}\u{1F000}-\u{1F2FF}\u{2600}-\u{27BF}\u{FE0F}]/u;

async function walk(directory, extensions) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const full = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (['node_modules', 'dist', '.git', '.data'].includes(entry.name)) continue;
      files.push(...(await walk(full, extensions)));
      continue;
    }
    if (extensions.includes(extname(entry.name))) files.push(full);
  }
  return files;
}

async function guardSources() {
  const files = await walk(root, ['.ts', '.mjs']);
  const problems = [];
  for (const file of files) {
    if (file === fileURLToPath(import.meta.url)) continue;
    const content = await readFile(file, 'utf8');
    for (const rule of BANNED_PATTERNS) {
      if (rule.pattern.test(content)) problems.push(`${relative(root, file)} → ${rule.label}`);
    }
  }
  if (problems.length > 0) {
    throw new Error(`Banned placeholders found:\n${problems.join('\n')}`);
  }
  return files.length;
}

async function guardFrontend() {
  const files = await walk(join(root, 'apps/frontend'), ['.html', '.css', '.js', '.svg']);
  const problems = [];
  for (const file of files) {
    if (file.endsWith('catalog.js')) continue;
    const content = await readFile(file, 'utf8');
    const match = content.match(EMOJI_PATTERN);
    if (match) problems.push(`${relative(root, file)} → ${match[0]}`);
  }
  if (problems.length > 0) {
    throw new Error(`Emoji found in frontend assets:\n${problems.join('\n')}`);
  }
  return files.length;
}

async function generateCatalog() {
  const { stdout } = await import('node:child_process').then(({ execFile }) =>
    new Promise((resolve, reject) => {
      execFile(process.execPath, ['--import', 'tsx', 'scripts/generate-catalog.mjs'], { cwd: root }, (error, stdout, stderr) => {
        if (error) reject(new Error(`${error.message}\n${stderr}`));
        else resolve({ stdout });
      });
    })
  );
  process.stdout.write(String(stdout));
}

async function emitInstallerAssets() {
  const target = join(root, 'apps/frontend/assets/installer');
  await mkdir(target, { recursive: true });
  const { SCHEMA_STATEMENTS } = await import('../packages/core/src/storage/schema.ts');
  const header = [
    '-- BotForge D1 schema',
    '-- Auto-generated by scripts/build.mjs — do not edit by hand.',
    ''
  ].join('\n');
  const schema = `${header}${SCHEMA_STATEMENTS.map((statement) => `${statement};`).join('\n\n')}\n`;
  await writeFile(join(target, 'schema.sql'), schema, 'utf8');

  return SCHEMA_STATEMENTS.length;
}

async function bundle() {
  const shared = {
    bundle: true,
    format: 'esm',
    target: 'node20',
    sourcemap: false,
    logLevel: 'info',
    define: { 'process.env.NODE_ENV': '"production"' }
  };

  await esbuild({
    ...shared,
    entryPoints: [join(root, 'apps/control-plane/src/main.ts')],
    outfile: join(dist, 'control-plane/main.js'),
    platform: 'node',
    external: NODE_EXTERNALS,
    banner: { js: '#!/usr/bin/env node' }
  });

  await esbuild({
    ...shared,
    entryPoints: [join(root, 'apps/control-plane/src/install.ts')],
    outfile: join(dist, 'install/main.js'),
    platform: 'node',
    external: NODE_EXTERNALS,
    banner: { js: '#!/usr/bin/env node' }
  });

  await esbuild({
    ...shared,
    entryPoints: [join(root, 'apps/cloudflare-worker/src/index.ts')],
    outfile: join(dist, 'cloudflare-worker/index.js'),
    platform: 'neutral',
    mainFields: ['module', 'main'],
    conditions: ['workerd', 'worker', 'browser'],
    external: ['node:*', 'pg']
  });
}

async function copyWorkerForInstaller() {
  const source = join(dist, 'cloudflare-worker/index.js');
  const bundleStat = await stat(source).catch(() => null);
  if (!bundleStat) throw new Error('cloudflare worker bundle missing; run the bundle step first');
  const target = join(root, 'apps/frontend/assets/installer/worker.js');
  await mkdir(dirname(target), { recursive: true });
  await cp(source, target);
  return bundleStat.size;
}

const ASSET_REFERENCE = /(href|src)="((?:\.\.\/)*)(assets\/[^"?#]+)"/g;

async function assetDigest(assetPath) {
  try {
    const content = await readFile(join(dist, 'frontend', assetPath));
    return createHash('sha256').update(content).digest('hex').slice(0, 10);
  } catch {
    return null;
  }
}

/* GitHub Pages serves static files with a ten minute shared cache, so a stale
 * wizard.js could load next to a fresh wizard.html and leave the template
 * picker empty. Every local asset reference is stamped with the content hash of
 * the file it points at: a changed file gets a brand new URL and the browser can
 * never pair mismatched revisions again. */
async function versionAssets() {
  const front = join(dist, 'frontend');
  const files = await walk(front, ['.html']);
  const digests = new Map();
  let references = 0;
  for (const file of files) {
    const source = await readFile(file, 'utf8');
    if (!source.includes('assets/')) continue;
    const base = relative(front, dirname(file));
    const resolve = (prefix, target) => join(base, prefix.replace(/\.\.\//g, '../'), target).split('\\').join('/');
    for (const [, , prefix, target] of source.matchAll(ASSET_REFERENCE)) {
      const resolved = resolve(prefix, target);
      if (digests.has(resolved)) continue;
      digests.set(resolved, await assetDigest(resolved));
    }
    const output = source.replace(ASSET_REFERENCE, (match, attribute, prefix, target) => {
      const digest = digests.get(resolve(prefix, target));
      if (!digest) return match;
      references += 1;
      return `${attribute}="${prefix}${target}?v=${digest}"`;
    });
    if (output !== source) await writeFile(file, output, 'utf8');
  }
  return references;
}

async function copyFrontend() {
  await rm(join(dist, 'frontend'), { recursive: true, force: true });
  await cp(join(root, 'apps/frontend'), join(dist, 'frontend'), { recursive: true });
  const catalog = await stat(join(dist, 'frontend/assets/js/catalog.js'));
  if (catalog.size < 1000) throw new Error('generated catalog is suspiciously small');
  const references = await versionAssets();
  if (references < 10) throw new Error('asset versioning did not stamp the frontend');
}

async function writeBuildInfo() {
  const info = {
    name: 'botforge',
    version: '1.0.0',
    builtAt: new Date().toISOString(),
    node: process.version,
    entries: {
      controlPlane: 'dist/control-plane/main.js',
      installer: 'dist/install/main.js',
      cloudflareWorker: 'dist/cloudflare-worker/index.js',
      frontend: 'dist/frontend'
    }
  };
  await writeFile(join(dist, 'build-info.json'), `${JSON.stringify(info, null, 2)}\n`, 'utf8');
}

async function main() {
  await mkdir(dist, { recursive: true });
  const guarded = await guardSources();
  console.log(`source guard: ${guarded} files checked`);
  const frontendFiles = await guardFrontend();
  console.log(`frontend guard: ${frontendFiles} files checked, no emoji`);
  await generateCatalog();
  const schemaStatements = await emitInstallerAssets();
  console.log(`installer schema: ${schemaStatements} statements`);
  await bundle();
  const workerBytes = await copyWorkerForInstaller();
  console.log(`installer worker bundle: ${Math.round(workerBytes / 1024)}kb`);
  await copyFrontend();
  await writeBuildInfo();
  console.log('build complete → dist/');
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
