#!/usr/bin/env node
/**
 * Generates apps/frontend/assets/js/catalog.js from the canonical bot templates.
 * Run with: node --import tsx scripts/generate-catalog.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { botTemplates, templateCategories } from '../packages/bot-templates/src/index.ts';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(root, 'apps/frontend/assets/js/catalog.js');

const bots = botTemplates.map((template, index) => ({
  id: template.id,
  number: index + 1,
  name: template.name,
  category: template.category,
  summary: template.summary,
  description: template.description,
  icon: template.icon,
  tags: template.tags,
  version: template.version,
  commands: template.commands.length,
  commandList: template.commands.map((command) => ({
    command: command.command,
    description: command.description,
    adminOnly: Boolean(command.adminOnly),
  })),
  menuCount: template.menu.length,
  requirements: template.requirements.map((requirement) => ({
    key: requirement.key,
    label: requirement.label,
    description: requirement.description,
    required: Boolean(requirement.required),
    env: requirement.env ?? null,
  })),
  defaultConfig: template.defaultConfig,
}));

const payload = {
  generatedAt: new Date().toISOString(),
  totals: {
    bots: bots.length,
    commands: bots.reduce((sum, bot) => sum + bot.commands, 0),
    categories: templateCategories.length,
    requirements: bots.reduce((sum, bot) => sum + bot.requirements.length, 0),
  },
  categories: templateCategories,
  bots,
};

const banner = '/* Auto-generated by scripts/generate-catalog.mjs — do not edit by hand. */\n';
const content = `${banner}window.BOTFORGE_CATALOG = ${JSON.stringify(payload, null, 2)};\n`;
await mkdir(dirname(target), { recursive: true });
await writeFile(target, content, 'utf8');

const totals = new Map();
for (const bot of bots) totals.set(bot.category, (totals.get(bot.category) ?? 0) + 1);
console.log(`catalog written: ${bots.length} bots, ${payload.totals.commands} commands`);
console.log([...totals.entries()].map(([category, count]) => `${category}=${count}`).join(' '));
